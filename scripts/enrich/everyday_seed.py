def resolve():
    """term → [(dictionary prefix, dictionary name)] for terms that exist exactly once in a dictionary."""
    found = defaultdict(list)
    want = {normalize(t): t for t in SEED}
    for d in complete_dictionaries():
        counts = defaultdict(int)
        for r in d["records"]:
            counts[normalize(r.get("term_without_diacritics") or r["term"])] += 1
        for key, n in counts.items():
            if key in want and n == 1:
                found[want[key]].append((d["dictionary_id"][:8], d["dictionary_name"].strip()))
    return found


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "resolve"
    found = resolve()
    if cmd == "resolve":
        for t in SEED:
            print(("✓ " if found.get(t) else "✗ ") + t, " | ".join(n for _, n in found.get(t, [])))
        print(sum(1 for t in SEED if found.get(t)), "of", len(SEED), "terms found")
        return
    by_dict = defaultdict(list)
    for t, forms in SEED.items():
        for pid, _ in found.get(t, []):
            chunk = " ; ".join(f"{f}|{k}|{'h' if k in 'ts' else 'm'}" for f, k in forms if re.fullmatch(r"[؀-ۿ ]+", f))
            if chunk:
                by_dict[pid].append(f"{t}\t{chunk}")
    out = ROOT / "data" / "dictionaries" / "enriched" / "variants" / "topic"
    for pid, lines in by_dict.items():
        head = "# Everyday and colloquial words written by Claude from knowledge of Arabic usage (scripts/enrich/everyday_seed.py)."
        (out / f"{pid}-everyday-seed-1.txt").write_text("\n".join([head] + lines) + "\n", encoding="utf-8")
        print(pid, len(lines))


if __name__ == "__main__":
    main()
