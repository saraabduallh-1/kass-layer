"""Enrich completed dictionaries: Qwen generates variants, Claude reviews and corrects them.

Run with the project virtualenv. Settings go in .env (never printed):
  QWEN_BASE_URL=https://<provider>/v1    QWEN_API_KEY=...    QWEN_MODEL=Qwen/Qwen3.5-4B
  ANTHROPIC_API_KEY=sk-ant-...

  .venv/bin/python scripts/enrich/enrich_dictionaries.py status
  .venv/bin/python scripts/enrich/enrich_dictionaries.py generate --dictionary <id> --limit 30   # Qwen pilot
  .venv/bin/python scripts/enrich/enrich_dictionaries.py review-pilot --dictionary <id> --limit 30  # Claude, prints before/after
  .venv/bin/python scripts/enrich/enrich_dictionaries.py generate                 # Qwen, every completed dictionary
  .venv/bin/python scripts/enrich/enrich_dictionaries.py review-submit            # Claude Batch API (50% price)
  .venv/bin/python scripts/enrich/enrich_dictionaries.py review-collect           # fetch results, then finalize

Commands:
  status          Per dictionary: senses, generated by Qwen, reviewed by Claude; open Claude batches.
  generate        Stage 1. Qwen proposes variants for every sense not generated yet (resumable, parallel).
  review-pilot    Stage 2 on a few senses with the regular API, printing Qwen's proposal next to Claude's result.
  review-submit   Stage 2 for every generated, unreviewed sense, through the Message Batches API.
  review-collect  Download finished batches, then finalize. Failed senses stay pending for the next submit.
  review-export   Write unreviewed senses to review_packs/<id>.pack.jsonl for review without the API
                  (for example by Claude inside a Claude Code session).
  review-import   Import that reviewer's decisions (JSONL: sense_id, variants, dropped), then finalize.
  chatgpt-prepare Split every completed dictionary into 200-sense parts under chatgpt/inputs/ and write
                  chatgpt/PROMPT.md (prompt + GitHub link per part) for a manual ChatGPT hand-off.
  chatgpt-import  Import ChatGPT's files from chatgpt/outputs/ (same folder and file names) as stage 1.
  chatgpt-status  Parts imported per dictionary.
  finalize        Re-run the cross-dictionary checks and write the enriched files and report.

Only Claude-reviewed variants can be accepted; Qwen-only variants stay in the review queue.
"""
