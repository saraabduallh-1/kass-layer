# Standard per-million-token prices, used only for the printed estimate; the Batch API halves them.
PRICES = {"claude-opus-5-5": (4.00, 20.00), "claude-sonnet-5-5": (2.00, 10.00)}


def _selected(args) -> list[dict]:
    dictionaries = complete_dictionaries()
    if getattr(args, "dictionary", None):
        dictionaries = [d for d in dictionaries if d["dictionary_id"] in args.dictionary]
        if not dictionaries:
            raise SystemExit(f"No completed dictionary matches {args.dictionary}")
    return dictionaries


def _anthropic():
    load_dotenv()
    try:
        import anthropic
    except ImportError:
        raise SystemExit("The anthropic package is missing: .venv/bin/pip install anthropic")
    return anthropic, anthropic.Anthropic()


def _in_flight(state: dict) -> set[str]:
    return {sense_id for batch in state["batches"].values() if not batch.get("collected")
            for chunk in batch["chunks"].values() for sense_id in chunk["sense_ids"]}


def _usage_dict(usage) -> dict[str, int]:
    fields = ("input_tokens", "output_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")
    return {field: getattr(usage, field, 0) or 0 for field in fields}


def _claude_text(message) -> str | None:
    if message.stop_reason in {"refusal", "max_tokens"}:
        return None
    return next((block.text for block in message.content if block.type == "text"), None)


# --------------------------------------------------------------------------- status


def cmd_status(args) -> None:
    state = load_state()
    print(f"{'senses':>7} {'qwen':>6} {'claude':>7}  dictionary")
    for dictionary in _selected(args):
        generations = current_generations(dictionary)
        reviewed = current_reviews(dictionary, generations)
        print(f"{len(dictionary['records']):>7} {len(generations):>6} {len(reviewed):>7}  "
              f"{dictionary_name(dictionary)} ({dictionary['dictionary_id']})")
    for batch_id, batch in state["batches"].items():
        if not batch.get("collected"):
            print(f"open Claude batch {batch_id}: {len(batch['chunks'])} requests, submitted {batch['created_at']}")


# --------------------------------------------------------------------------- stage 1: Qwen


def cmd_generate(args) -> None:
    load_dotenv()
    try:
        client = QwenClient(model=args.model, response_format=args.response_format, thinking=args.thinking)
    except QwenError as error:
        raise SystemExit(str(error))
    lock = threading.Lock()
    selected = _selected(args)
    for dictionary in (reversed(selected) if args.reverse else selected):
        senses = pending_generation(dictionary)
        if args.limit is not None:
            senses = senses[: args.limit]
        if not senses:
            continue
        name = dictionary_name(dictionary)
        path = QWEN_DIR / f"{dictionary['dictionary_id']}.jsonl"
        work = chunks(senses, args.chunk_size)
        print(f"== {name}: {len(senses)} senses in {len(work)} requests ({args.workers} parallel)", flush=True)
        counts: Counter = Counter()

        def run(chunk):
            text, _ = client.complete(generation_messages(name, chunk), GENERATION_SCHEMA)
            return chunk, parse_items(extract_json(text), len(chunk))

        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            futures = [pool.submit(run, chunk) for chunk in work]
            for done, future in enumerate(as_completed(futures), start=1):
                try:
                    chunk, parsed = future.result()
                except QwenError as error:
                    counts["failed_requests"] += 1
                    print(f"  request failed: {error}", flush=True)
                    continue
                except (json.JSONDecodeError, KeyError, IndexError, TypeError):
                    counts["unparseable_replies"] += 1
                    continue
                rows = generation_rows(dictionary, chunk, parsed, client.model)
                with lock:
                    append_jsonl(path, rows)
                counts["senses_written"] += len(rows)
                counts["senses_missing_from_reply"] += len(chunk) - len(rows)
                if done % 20 == 0 or done == len(work):
                    print(f"  {done}/{len(work)} requests, {counts['senses_written']} senses saved", flush=True)
        print(f"  {dict(counts)}  (anything missing stays pending; rerun generate to retry)", flush=True)
    report = finalize(complete_dictionaries())
    print(f"finalize: generated={report['totals']['generated']} reviewed={report['totals']['reviewed']}")


# --------------------------------------------------------------------------- stage 2: Claude review


def cmd_review_pilot(args) -> None:
    anthropic, client = _anthropic()
    state = load_state()
    dictionary = _selected(args)[0]
    name = dictionary_name(dictionary)
    pairs = pending_review(dictionary, in_flight=_in_flight(state))[: args.limit]
    if not pairs:
        print("Nothing to review: run `generate` for this dictionary first.")
        return
    written, usages = [], []
    for chunk in chunks(pairs, args.chunk_size):
        try:
            # Server-side fallback: if a safety classifier declines, the API reruns the request on a fallback model.
            message = client.beta.messages.create(
                betas=["server-side-fallback-2026-07-01"], fallbacks="default",
                **review_params(name, chunk, args.model, args.effort))
        except anthropic.APIStatusError as error:
            print(f"API error {error.status_code}: {error.message}")
            break
        except anthropic.APIConnectionError:
            print("Network error; the remaining senses stay pending.")
            break
        usages.append(_usage_dict(message.usage))
        text = _claude_text(message)
        if text is None:
            print(f"Chunk skipped: stop_reason={message.stop_reason}")
            continue
        rows = review_rows(dictionary, chunk, parse_items(json.loads(text), len(chunk)), args.model, "sync")
        append_jsonl(REVIEW_DIR / f"{dictionary['dictionary_id']}.jsonl", rows)
        written.extend(row["sense_id"] for row in rows)
    state["sync_usage"].extend(usages)
    write_json(STATE_PATH, state)

    finalize(complete_dictionaries(), state=state)
    proposals = {sense_id: row for sense_id, row in current_generations(dictionary).items()}
    final = {r["sense_id"]: r for r in read_jsonl(OUT_DIR / f"{dictionary['dictionary_id']}.variants.jsonl")}
    print(f"\n{len(written)} senses reviewed from {name}\n")
    for sense_id in written:
        record = final[sense_id]
        qwen_forms = [v["form"] for v in proposals[sense_id]["variants"]]
        print(f"■ {record['term']}\n    Qwen:   {'، '.join(qwen_forms) or '(none)'}")
        for v in record["variants"]:
            flag = "✓" if v["status"] == "accepted" else "? " + ",".join(v["review_reasons"])
            fixed = f" (was: {v['original_form']})" if v.get("original_form") else ""
            print(f"    {flag:<3} {v['form']}{fixed}  [{v['type']}, {v['confidence']}, {v.get('action')}]  — {v['example']}")
            if v["ambiguity_note"]:
                print(f"         ملاحظة: {v['ambiguity_note']}")
        for d in record["dropped"]:
            print(f"    ✗ {d['form']}  ({d['reason']})")
    _print_estimate(usages, len(written), args.model)


def _print_estimate(usages: list[dict], senses_done: int, model: str) -> None:
    if not senses_done or model not in PRICES:
        return
    tokens_in = sum(u["input_tokens"] for u in usages)
    tokens_out = sum(u["output_tokens"] for u in usages)
    price_in, price_out = PRICES[model]
    per_sense = (tokens_in * price_in + tokens_out * price_out) / 1_000_000 / senses_done
    total = sum(len(d["records"]) for d in complete_dictionaries())
    print(f"\nThis pilot: {tokens_in} input + {tokens_out} output tokens (~${per_sense * senses_done:.2f}).")
    print(f"Estimate to review all {total} senses with the Batch API: ~${per_sense * total / 2:.0f}")


def cmd_review_submit(args) -> None:
    _, client = _anthropic()
    from anthropic.types.message_create_params import MessageCreateParamsNonStreaming
    from anthropic.types.messages.batch_create_params import Request

    state = load_state()
    in_flight = _in_flight(state)
    requests, mapping = [], {}
    for dictionary in _selected(args):
        name = dictionary_name(dictionary)
        for chunk in chunks(pending_review(dictionary, in_flight=in_flight), args.chunk_size):
            custom_id = f"r{len(requests):06d}"
            requests.append(Request(custom_id=custom_id, params=MessageCreateParamsNonStreaming(
                **review_params(name, chunk, args.model, args.effort))))
            mapping[custom_id] = {"dictionary_id": dictionary["dictionary_id"],
                                  "sense_ids": [record["sense_id"] for record, _ in chunk]}
    if not requests:
        print("Nothing to review: every generated sense is reviewed or already in an open batch.")
        return
    batch = client.messages.batches.create(requests=requests)
    state["batches"][batch.id] = {"created_at": datetime.now(timezone.utc).isoformat(), "model": args.model,
                                  "effort": args.effort, "chunks": mapping, "collected": False, "usage": {}}
    write_json(STATE_PATH, state)
    print(f"Submitted batch {batch.id}: {len(requests)} requests, "
          f"{sum(len(c['sense_ids']) for c in mapping.values())} senses. Run `review-collect` later.")


def cmd_review_collect(args) -> None:
    _, client = _anthropic()
    state = load_state()
    dictionaries = {d["dictionary_id"]: d for d in complete_dictionaries()}
    for batch_id, batch in state["batches"].items():
        if batch.get("collected"):
            continue
        remote = client.messages.batches.retrieve(batch_id)
        if remote.processing_status != "ended":
            counts = remote.request_counts
            print(f"{batch_id}: {remote.processing_status} (processing={counts.processing}, succeeded={counts.succeeded})")
            continue
        outcome: Counter = Counter()
        usage: Counter = Counter()
        for result in client.messages.batches.results(batch_id):
            chunk_info = batch["chunks"].get(result.custom_id)
            if chunk_info is None:
                continue
            if result.result.type != "succeeded":
                outcome[result.result.type] += 1
                continue
            message = result.result.message
            usage.update(_usage_dict(message.usage))
            text = _claude_text(message)
            dictionary = dictionaries.get(chunk_info["dictionary_id"])
            if text is None or dictionary is None:
                outcome[f"skipped_{message.stop_reason}"] += 1
                continue
            # Rebuild the exact (record, generation) pairs that were sent; a regenerated sense no longer matches.
            pending = {record["sense_id"]: (record, generation) for record, generation in pending_review(dictionary)}
            pairs = [pending[sense_id] for sense_id in chunk_info["sense_ids"] if sense_id in pending]
            if len(pairs) != len(chunk_info["sense_ids"]):
                outcome["stale_chunks"] += 1
                continue
            rows = review_rows(dictionary, pairs, parse_items(json.loads(text), len(pairs)), batch["model"],
                               f"batch:{batch_id}")
            append_jsonl(REVIEW_DIR / f"{dictionary['dictionary_id']}.jsonl", rows)
            outcome["senses_written"] += len(rows)
        batch["collected"] = True
        batch["usage"] = dict(usage)
        batch["outcome"] = dict(outcome)
        write_json(STATE_PATH, state)
        print(f"{batch_id}: collected {dict(outcome)}")
    report = finalize(list(dictionaries.values()), state=state)
    print(f"finalize: {json.dumps(report['totals'], ensure_ascii=False)}")


REVIEW_PACK_DIR = OUT_DIR / "review_packs"
SESSION_REVIEWER = "claude-opus-5-5 (Claude Code session)"


def cmd_review_export(args) -> None:
    """Write unreviewed senses to a pack file that a reviewer (e.g. Claude in a Claude Code session) fills in."""
    state = load_state()
    REVIEW_PACK_DIR.mkdir(parents=True, exist_ok=True)
    for dictionary in _selected(args):
        pairs = pending_review(dictionary, in_flight=_in_flight(state))[: args.limit]
        if not pairs:
            continue
        path = REVIEW_PACK_DIR / f"{dictionary['dictionary_id']}.pack.jsonl"
        path.unlink(missing_ok=True)
        append_jsonl(path, [
            {"sense_id": record["sense_id"], "term": record.get("term_without_diacritics") or record["term"],
             "definition": (record.get("definition") or "").strip(), "english": record.get("english_term") or "",
             "proposed": [{k: v.get(k) for k in ("form", "type", "confidence", "ambiguous", "example")}
                          for v in generation["variants"]]}
            for record, generation in pairs
        ])
        print(f"{len(pairs)} senses -> {path.relative_to(ROOT)}")


def cmd_review_import(args) -> None:
    """Import reviewer decisions: one JSON line per sense with sense_id, variants (review schema) and dropped."""
    decisions = {row["sense_id"]: row for row in read_jsonl(Path(args.file))}
    counts: Counter = Counter()
    for dictionary in complete_dictionaries():
        pending = {record["sense_id"]: (record, generation) for record, generation in pending_review(dictionary)}
        matched = [(pending[sense_id], decision) for sense_id, decision in decisions.items() if sense_id in pending]
        if not matched:
            continue
        pairs = [pair for pair, _ in matched]
        parsed = {index: decision for index, (_, decision) in enumerate(matched, start=1)}
        rows = review_rows(dictionary, pairs, parsed, SESSION_REVIEWER, f"session:{Path(args.file).name}")
        append_jsonl(REVIEW_DIR / f"{dictionary['dictionary_id']}.jsonl", rows)
        counts["senses_imported"] += len(rows)
    counts["not_pending_or_stale"] = len(decisions) - counts["senses_imported"]
    print(dict(counts))
    report = finalize(complete_dictionaries())
    print(f"finalize: {json.dumps(report['totals'], ensure_ascii=False)}")


CHATGPT_INPUTS = CHATGPT_DIR / "inputs"
CHATGPT_OUTPUTS = CHATGPT_DIR / "outputs"
RAW_BASE = "https://raw.githubusercontent.com/saraabduallh-1/kass-layer/main"
# First-experiment dictionaries go first: Data & AI, Digital Government, Finance, Media, Qiyas.
CHATGPT_PRIORITY = ["4cd164a7-7160-4de8-af5c-34382f5da657", "97ac5360-d65f-425f-974f-9118f09d13a6",
                    "4264f8ae-7c51-437d-a6e4-877abad57325", "928f4f87-b98c-4b2d-b31d-0b45c6747644",
                    "7806f9cf-4bdb-4c10-b9e5-2705d8945603"]


def _chatgpt_dictionaries() -> list[tuple[str, dict]]:
    """(folder name, dictionary) in hand-off order; the folder name is stable across runs."""
    dictionaries = complete_dictionaries()
    rank = {dictionary_id: i for i, dictionary_id in enumerate(CHATGPT_PRIORITY)}
    dictionaries.sort(key=lambda d: (rank.get(d["dictionary_id"], len(rank)), dictionary_name(d)))
    return [(f"{i:02d}-{d['dictionary_id']}", d) for i, d in enumerate(dictionaries, start=1)]


def cmd_chatgpt_prepare(args) -> None:
    """Write ChatGPT input parts (never the sources), the prompt and an index with GitHub links."""
    lines = ["# إثراء المعاجم عبر ChatGPT", "",
             "لكل جزء: افتحي محادثة ChatGPT، والصقي الرسالة الجاهزة تحت الجزء، ونزّلي الملف اللي يرجعه،",
             f"واحفظيه بنفس الاسم في `{CHATGPT_OUTPUTS.relative_to(ROOT)}/<نفس اسم المجلد>/`.", "",
             "## البرومبت (مشترك لكل الأجزاء)", "", "```", CHATGPT_PROMPT, "```", ""]
    total_parts = 0
    for folder, dictionary in _chatgpt_dictionaries():
        parts = chatgpt_parts(dictionary)
        lines += [f"## {folder[:2]}. {dictionary_name(dictionary)} — {len(dictionary['records'])} معنى، {len(parts)} أجزاء", ""]
        for number, part in enumerate(parts, start=1):
            path = CHATGPT_INPUTS / folder / f"part-{number:03d}.jsonl"
            path.unlink(missing_ok=True)
            append_jsonl(path, chatgpt_input_lines(part))
            url = f"{RAW_BASE}/{path.relative_to(ROOT).as_posix()}"
            lines += [f"- `{folder}/part-{number:03d}.jsonl` ({len(part)} معنى): "
                      f"الرسالة ← البرومبت أعلاه ثم: `Input file: {url}`"]
            total_parts += 1
        lines.append("")
    (CHATGPT_OUTPUTS).mkdir(parents=True, exist_ok=True)
    (CHATGPT_OUTPUTS / ".gitkeep").touch()
    (CHATGPT_DIR / "PROMPT.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{total_parts} parts written under {CHATGPT_INPUTS.relative_to(ROOT)}; "
          f"prompt and links in {(CHATGPT_DIR / 'PROMPT.md').relative_to(ROOT)}")


def cmd_chatgpt_import(args) -> None:
    """Import every new or changed ChatGPT output file as stage-1 generations."""
    state = load_state()
    imported = state.setdefault("chatgpt_imported", {})
    totals: Counter = Counter()
    for folder, dictionary in _chatgpt_dictionaries():
        parts = chatgpt_parts(dictionary)
        for number, part in enumerate(parts, start=1):
            output = CHATGPT_OUTPUTS / folder / f"part-{number:03d}.jsonl"
            if not output.exists():
                continue
            digest = hashlib.sha256(output.read_bytes()).hexdigest()
            key = output.relative_to(ROOT).as_posix()
            if imported.get(key, {}).get("sha256") == digest:
                continue
            rows, problems = import_chatgpt_part(dictionary, part, output, args.model)
            append_jsonl(QWEN_DIR / f"{dictionary['dictionary_id']}.jsonl", rows)
            imported[key] = {"sha256": digest, "senses": len(rows), "problems": problems,
                             "imported_at": datetime.now(timezone.utc).isoformat()}
            totals["parts"] += 1
            totals["senses"] += len(rows)
            flag = "" if not any(problems.values()) else f"  problems={problems}"
            print(f"{key}: {len(rows)}/{len(part)} senses{flag}")
    write_json(STATE_PATH, state)
    print(f"imported {dict(totals) or 'nothing new'}")
    if totals:
        report = finalize(complete_dictionaries(), state=state)
        print(f"finalize: generated={report['totals']['generated']} reviewed={report['totals']['reviewed']}")


def cmd_chatgpt_status(args) -> None:
    state = load_state().get("chatgpt_imported", {})
    for folder, dictionary in _chatgpt_dictionaries():
        parts = chatgpt_parts(dictionary)
        done = sum((CHATGPT_OUTPUTS / folder / f"part-{n:03d}.jsonl").relative_to(ROOT).as_posix() in state
                   for n in range(1, len(parts) + 1))
        print(f"{done:>3}/{len(parts):<3} parts  {folder}  {dictionary_name(dictionary)}")


def cmd_finalize(args) -> None:
    print(json.dumps(finalize(complete_dictionaries())["totals"], ensure_ascii=False, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    handlers = {"status": cmd_status, "generate": cmd_generate, "review-pilot": cmd_review_pilot,
                "review-submit": cmd_review_submit, "review-collect": cmd_review_collect,
                "review-export": cmd_review_export, "review-import": cmd_review_import,
                "chatgpt-prepare": cmd_chatgpt_prepare, "chatgpt-import": cmd_chatgpt_import,
                "chatgpt-status": cmd_chatgpt_status, "finalize": cmd_finalize}
    for name, handler in handlers.items():
        sub = commands.add_parser(name)
        sub.set_defaults(handler=handler)
        if name in {"status", "generate", "review-pilot", "review-submit", "review-export"}:
            sub.add_argument("--dictionary", action="append", help="dictionary id (repeatable); default: all completed")
        if name == "generate":
            sub.add_argument("--model", help="Qwen model name (default: QWEN_MODEL or Qwen/Qwen3.5-4B)")
            sub.add_argument("--limit", type=int, help="senses per dictionary, for a pilot")
            sub.add_argument("--chunk-size", type=int, default=QWEN_CHUNK_SIZE)
            sub.add_argument("--workers", type=int, default=4, help="parallel requests")
            sub.add_argument("--reverse", action="store_true",
                             help="process dictionaries in reverse order (lets a second process work from the other end)")
            sub.add_argument("--response-format", default="none", choices=["json_schema", "json_object", "none"],
                             help="none (default) lets the model answer freely; json_schema made Qwen3.5-4B return empty lists")
            sub.add_argument("--thinking", action=argparse.BooleanOptionalAction, default=False,
                             help="Qwen thinking mode; off by default (far slower, often cut off)")
        if name in {"review-pilot", "review-submit"}:
            sub.add_argument("--model", default=DEFAULT_CLAUDE_MODEL)
            sub.add_argument("--effort", default=DEFAULT_CLAUDE_EFFORT, choices=["low", "medium", "high", "xhigh", "max"])
            sub.add_argument("--chunk-size", type=int, default=REVIEW_CHUNK_SIZE)
        if name == "review-pilot":
            sub.add_argument("--limit", type=int, default=30)
        if name == "review-export":
            sub.add_argument("--limit", type=int, help="senses per dictionary")
        if name == "chatgpt-import":
            sub.add_argument("--model", default="chatgpt", help="label stored with each row, e.g. the ChatGPT model used")
        if name == "review-import":
            sub.add_argument("file", help="JSONL of decisions: sense_id, variants, dropped")
    args = parser.parse_args()
    if args.command == "review-pilot" and not args.dictionary:
        parser.error("review-pilot needs --dictionary")
    args.handler(args)


if __name__ == "__main__":
    main()
